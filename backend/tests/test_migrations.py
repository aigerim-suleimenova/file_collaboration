"""Migrations build and tear down the real schema (specs/database-migrations).

Needs PostgreSQL: set TEST_POSTGRES_URL to an empty, throwaway database, e.g.
postgresql+psycopg2://postgres:pw@localhost:5432/fc_test. Skipped otherwise.
"""

import os
from pathlib import Path

import pytest
import sqlalchemy as sa
from alembic import command
from alembic.config import Config
from alembic.util import AutogenerateDiffsDetected
from sqlmodel import SQLModel

pytestmark = pytest.mark.integration

DATABASE_URL = os.environ.get("TEST_POSTGRES_URL")
BACKEND_DIR = Path(__file__).resolve().parent.parent

if not DATABASE_URL:
    pytest.skip("TEST_POSTGRES_URL not set", allow_module_level=True)


@pytest.fixture()
def alembic_config() -> Config:
    config = Config(str(BACKEND_DIR / "alembic.ini"))
    config.set_main_option("script_location", str(BACKEND_DIR / "app" / "alembic"))
    config.attributes["database_url"] = DATABASE_URL
    command.downgrade(config, "base")
    yield config
    command.downgrade(config, "base")


def public_tables() -> set[str]:
    engine = sa.create_engine(DATABASE_URL)
    try:
        return set(sa.inspect(engine).get_table_names()) - {"alembic_version"}
    finally:
        engine.dispose()


def file_columns() -> set[str]:
    engine = sa.create_engine(DATABASE_URL)
    try:
        return {c["name"] for c in sa.inspect(engine).get_columns("file")}
    finally:
        engine.dispose()


def test_upgrade_check_downgrade_upgrade(alembic_config):
    command.upgrade(alembic_config, "head")
    assert {"user", "file"} <= public_tables()
    assert "yjs_state" in file_columns()

    command.check(alembic_config)  # raises if the models and schema differ

    command.downgrade(alembic_config, "base")
    assert not ({"user", "file"} & public_tables())

    command.upgrade(alembic_config, "head")
    assert {"user", "file"} <= public_tables()


def test_check_fails_when_a_model_has_no_migration(alembic_config):
    command.upgrade(alembic_config, "head")
    extra = sa.Table(
        "unmigrated_example", SQLModel.metadata, sa.Column("id", sa.Integer, primary_key=True)
    )
    try:
        with pytest.raises(AutogenerateDiffsDetected):
            command.check(alembic_config)
    finally:
        SQLModel.metadata.remove(extra)
